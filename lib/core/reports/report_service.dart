/// Centralized report generation service.
/// All reports share: Company header, user info, date, title, professional layout.
class ReportService {
  ReportService._();

  static final _dateFormat = DateFormat('dd-MM-yyyy hh:mm a');
  static pw.MemoryImage? _crescentBrandImage;

  // ─── Calibration Report ──────────────────────────────────────────────────

  static Future<void> printCalibrationReport({
    required BuildContext context,
    required String deviceId,
    required String deviceType, // 'ph' or 'ec'
    required String mode, // '3' or '5'
    required List<CalibrationRow> rows,
    String? probe,
  }) async {
    final company = await AppDatabase.instance.getCompanyDetails();
    final user = AuthService.instance.currentUser;
    final now = DateTime.now();
    final brandImage = await _loadCrescentBrandImage();

    final pdf = pw.Document();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(40),
        header: (ctx) =>
            _buildHeader(company, 'Calibration Report', now, brandImage),
        footer: (ctx) => _buildFooter(ctx, user, brandImage),
        build: (ctx) => [
          pw.SizedBox(height: 16),
          // Device Info
          _infoRow('Device ID', deviceId),
          _infoRow('Device Type', deviceType.toUpperCase()),
          _infoRow('Mode', '$mode Point Calibration'),
          if (probe != null && probe.isNotEmpty) _infoRow('Probe', probe),
          _infoRow('Calibration Date', _dateFormat.format(now)),
          _infoRow('Generated By', user?.name ?? 'N/A'),
          pw.SizedBox(height: 16),

          // Calibration Table
          pw.TableHelper.fromTextArray(
            context: ctx,
            border: pw.TableBorder.all(color: PdfColors.grey400, width: 0.5),
            headerStyle: pw.TextStyle(
              fontWeight: pw.FontWeight.bold,
              fontSize: 9,
              color: PdfColors.white,
            ),
            headerDecoration: const pw.BoxDecoration(color: PdfColor(0.2, 0.4, 0.7)),
            cellStyle: const pw.TextStyle(fontSize: 8),
            cellPadding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 4),
            headerAlignments: {
              0: pw.Alignment.center,
              1: pw.Alignment.center,
              2: pw.Alignment.center,
              3: pw.Alignment.center,
              4: pw.Alignment.center,
              5: pw.Alignment.center,
            },
            cellAlignments: {
              0: pw.Alignment.center,
              1: pw.Alignment.center,
              2: pw.Alignment.center,
              3: pw.Alignment.center,
              4: pw.Alignment.center,
              5: pw.Alignment.center,
            },
            headers: [
              deviceType == 'ec' ? 'EC' : 'pH',
              '${deviceType == 'ec' ? 'EC' : 'pH'} After Cal',
              'Slope',
              'Temp (°C)',
              'mV',
              'Date & Time',
            ],
            data: rows.asMap().entries.map((entry) {
              final idx = entry.key;
              final r = entry.value;
              return [
                r.val.toString(),
                r.valAfterCal?.toStringAsFixed(2) ?? '--',
                idx == 0 ? '--' : (r.slope?.toStringAsFixed(4) ?? '--'),
                r.temp?.toStringAsFixed(1) ?? '--',
                r.mv?.toStringAsFixed(2) ?? '--',
                r.time != null ? _dateFormat.format(r.time!) : '--',
              ];
            }).toList(),
          ),

          pw.SizedBox(height: 24),
          _remarksSection(),
        ],
      ),
    );
    final savedPath = await _saveAndRecord(
      pdf: pdf,
      fileName: 'Calibration_Report_$deviceId',
      reportType: 'calibration',
      deviceId: deviceId,
      deviceType: deviceType,
    );
    if (context.mounted) {
      await _showPrintPreview(context, pdf, savedPath.$2);
    }
  }

